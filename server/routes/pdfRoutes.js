const express = require('express');
const router = express.Router();
const PDFDocument = require('pdfkit');
const { verifyToken } = require('../middleware/authMiddleware'); // Ensure user is logged in
const { admin, db } = require('../utils/firebase');

router.post('/generate-pdf', verifyToken, async (req, res) => {
    const { route } = req.body;

    if (!route) {
        return res.status(400).json({ error: 'No route data provided' });
    }

    try {
        // Double check permission (canSave)
        const userRef = db.collection('users').doc(req.user.uid);
        const doc = await userRef.get();
        if (!doc.exists) return res.status(404).json({ error: 'User not found' });

        const userData = doc.data();
        // Check if user has 'canSave' feature or is admin/premium
        // Prompt says: "If canSave = false -> locked".
        // We assume frontend checks too, but backend must enforce.
        if (!userData.features || !userData.features.canSave) {
            return res.status(403).json({ error: 'Upgrade required to save routes (PDF)' });
        }

        const docPDF = new PDFDocument();

        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader('Content-Disposition', 'attachment; filename=route_summary.pdf');

        docPDF.pipe(res);

        // -- PDF Content --
        docPDF.fontSize(20).text('Traavo - Trip Summary', { align: 'center' });
        docPDF.moveDown();

        docPDF.fontSize(14).text(`From: ${route.steps ? route.steps[0].from : (route.source || 'Origin')}`);
        docPDF.text(`To: ${route.steps ? route.steps[route.steps.length - 1].to : (route.destination || 'Destination')}`);
        docPDF.text(`Total Time: ${route.totalTime || 'N/A'}`);
        docPDF.text(`Total Distance: ${route.totalDistanceKm ? route.totalDistanceKm + ' km' : 'N/A'}`);
        // docPDF.text(`Total Cost: ₹${route.totalCost || 'N/A'}`); // Cost might not be available in all objects
        docPDF.moveDown();

        docPDF.fontSize(16).text('Detail:', { underline: true });
        docPDF.moveDown(0.5);

        const steps = route.steps || route.segments || route.hops || [];

        if (Array.isArray(steps)) {
            steps.forEach((step, index) => {
                // Header: Step 1: Bus (Operator)
                docPDF.fontSize(12).font('Helvetica-Bold')
                    .text(`Step ${index + 1}: ${step.mode} ${step.operator ? `(${step.operator})` : ''}`);

                docPDF.font('Helvetica').fontSize(10);

                // From -> To
                docPDF.text(`From: ${step.from}`);
                docPDF.text(`To:   ${step.to}`);

                // Times & Duration
                const duration = step.durationMins ? `${Math.floor(step.durationMins / 60)}h ${step.durationMins % 60}m` : '';
                docPDF.text(`Time: ${step.depTime || '--'} -> ${step.arrTime || '--'} ${duration ? `(${duration})` : ''}`);

                // Distance
                if (step.distanceKm) {
                    docPDF.text(`Distance: ${Math.round(step.distanceKm)} km`);
                }

                // Platform / Extras
                if (step.platform) {
                    docPDF.text(`Platform: ${step.platform}`);
                }

                docPDF.moveDown();
            });
        }

        docPDF.fontSize(10).text('Generated by Traavo', { align: 'center', baseline: 'bottom' });

        docPDF.end();

    } catch (error) {
        console.error("PDF Generation Error:", error);
        res.status(500).json({ error: 'Could not generate PDF' });
    }
});

module.exports = router;
